int PixelGlyphIndex(char pCharacter)
{
    if (pCharacter >= 'a' && pCharacter <= 'z')
        return 38 + pCharacter - 'a';
    if (pCharacter >= 'A' && pCharacter <= 'Z')
        return pCharacter - 'A';
    if (pCharacter >= '0' && pCharacter <= '9')
        return 26 + pCharacter - '0';
    if (pCharacter == '_')
        return 36;
    if (pCharacter == '-')
        return 37;
    if (pCharacter == '?')
        return 64;
    return -1;
}

